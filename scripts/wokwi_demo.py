"""Record a few incidents from the study and write them into board/wokwi/sketch.ino, so the board
can replay them when no study is connected (a shared Wokwi link opened by anyone).

    python scripts/wokwi_demo.py                # rewrite the DEMO block in board/wokwi/sketch.ino
    python scripts/wokwi_demo.py --print-only   # print generated C++ DEMO block without editing sketch.ino

Each incident is the same frames scripts/panel_bridge.py would send: OpenDSS fault, ML zone,
restoration plan. Which one plays depends on the failure switches (none, SENSOR OFFLINE, SWITCH STUCK)
or Tier-1 HIF detection (DEMO_HIF, SLG 400 ohm with verified C99 HIF vector).
Needs models/model.pkl (run `python run.py` first). Simulation only.
"""
from __future__ import annotations

import argparse
import json
import pickle
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # run from anywhere

from shf import config, feeder, panel, restoration, topology

sys.path.insert(0, str(Path(__file__).resolve().parent))
from panel_bridge import incident, verified_hif_alert  # noqa: E402

SKETCH = config.ROOT / "board" / "wokwi" / "sketch.ino"
BEGIN, END = "// BEGIN DEMO (generated by scripts/wokwi_demo.py)", "// END DEMO"
# (label, bus, phase, ohms, seed, sensor offline, switch stuck, hif): one per demo scenario
CASES = [("normal", "60", "1", 25, 1, False, False, False),
         ("sensor", "60", "1", 25, 1, True, False, False),
         ("stuck", "35", "1", 25, 1, False, True, False),
         ("hif", "18", "1", 400, 1, False, False, True)]


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_demo_lines() -> tuple[list[str], list[str]]:
    with open(config.MODELS / "model.pkl", "rb") as f:
        bundle = pickle.load(f)
    feeder.load_feeder()
    zones = topology.find_zones()
    restoration.reset(zones)
    lines = [BEGIN,
             "// Recorded study frames, replayed when no study answers (shared link). Do not edit by hand.",
             f'const char* DEMO_IDLE = {c_string(json.dumps(panel.idle_frame(zones), separators=(",", ":")))};']
    summaries: list[str] = []
    for label, bus, ph, r, seed, sensor, stuck, is_hif in CASES:
        hif_alert = verified_hif_alert(r) if is_hif else None
        summary, now, after = incident(zones, bundle, bus, ph, r, seed, sensor, stuck, hif=hif_alert)
        restoration.reset(zones)
        frames = [json.dumps(f, separators=(",", ":")) for f in now]
        tail = [json.dumps(f, separators=(",", ":")) for f in after]
        lines.append(f"// {label}: fault bus {bus}, {r} ohm; true zone {summary['true_zone']}, "
                     f"ML zone {summary['predicted_zone']}")
        lines.append(f"const char* DEMO_{label.upper()}[] = {{" + ", ".join(c_string(x) for x in frames) + "};")
        lines.append(f"const char* DEMO_{label.upper()}_TIES[] = {{" +
                     (", ".join(c_string(x) for x in tail) or '""') + "};")
        lines.append(f"const int DEMO_{label.upper()}_N = {len(frames)}, DEMO_{label.upper()}_TIES_N = {len(tail)};")
        summaries.append(f"{label}: {len(frames)} frames + {len(tail)} after CLOSE TIES "
                         f"(true {summary['true_zone']}, ML {summary['predicted_zone']})")
    lines.append(END)
    return lines, summaries


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print-only", action="store_true",
                    help="print generated demo block without modifying board/wokwi/sketch.ino")
    args = ap.parse_args()

    lines, summaries = build_demo_lines()
    for msg in summaries:
        print(msg)
    if args.print_only:
        print("\n".join(lines))
        return
    s = SKETCH.read_bytes().decode("utf-8")
    i, j = s.index(BEGIN), s.index(END) + len(END)
    SKETCH.write_bytes((s[:i] + "\n".join(lines) + s[j:]).encode("utf-8"))
    print(f"wrote demo frames into {SKETCH.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
